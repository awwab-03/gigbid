"""The single marketplace port (R1).

Every marketplace capability the agents use is one of these operations, exposed as tools of the
Marketplace MCP server (mcp_servers/marketplace/server.py). The server delegates to exactly one
backend chosen by config (MARKETPLACE_MODE / marketplace.mode):

    gigsim       -> mcp_servers/marketplace/adapters/gigsim.py      (REST simulator)
    upwork_live  -> mcp_servers/marketplace/adapters/upwork_live.py (official Upwork MCP, OAuth 2.1)

Agents call the port through agent/mcp_client.py with per-agent allowlists, so neither the graph nor
any node can tell which marketplace is behind it.
"""

from __future__ import annotations

from typing import Any, Protocol

from mcp_servers.marketplace.adapters.base import MarketplaceBackend


class MarketplacePort(Protocol):
    async def search_jobs(self, query: str, **filters: Any) -> dict: ...
    async def get_job(self, job_id: str) -> dict: ...
    async def get_client_history(self, client_id: str) -> dict: ...
    async def get_connects_balance(self) -> dict: ...
    async def get_pricing_stats(self, category: str, budget_type: str) -> dict: ...
    async def get_policy(self) -> dict: ...
    async def list_threads(self) -> dict: ...
    async def list_messages(self, thread_id: str) -> dict: ...
    async def list_proposals(self, status: str | None = None) -> dict: ...
    async def get_events(self, since_id: int = 0) -> dict: ...
    async def create_proposal_draft(self, payload: dict, idempotency_key: str, dry_run: bool = False) -> dict: ...
    async def submit_proposal(self, proposal_id: str, idempotency_key: str, dry_run: bool = False) -> dict: ...
    async def send_message(self, thread_id: str, body: str, idempotency_key: str, dry_run: bool = False) -> dict: ...


__all__ = ["MarketplacePort", "MarketplaceBackend"]
