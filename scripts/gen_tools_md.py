"""Generate docs/TOOLS.md from the MCP schema snapshots (tests/contract/snapshots) so it never drifts."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
AUTH = {"portfolio": "Bearer service token (HTTP) / none (stdio)", "marketplace": "Bearer service token; GigSim HMAC token or Upwork OAuth 2.1 upstream",
        "workspace": "Bearer service token"}
OWNER = {"portfolio": "Fit Matcher, Writer, verifier, Critic", "marketplace": "Scout, Risk, Pricing, Compliance, Liaison, submitter",
         "workspace": "Client Liaison"}

rows = []
for server in ("portfolio", "marketplace", "workspace"):
    snap = json.loads((ROOT / "tests" / "contract" / "snapshots" / f"{server}.json").read_text(encoding="utf-8"))
    for name, t in snap.items():
        a = t.get("annotations") or {}
        rw = "read" if a.get("readOnlyHint") else "write"
        ann = ", ".join(f"{k.replace('Hint', '')}={str(v).lower()}" for k, v in a.items() if k.endswith("Hint"))
        req = ", ".join(t["input"].get("required", [])) or "-"
        rows.append(f"| `{name}` | {server} | {rw} | {ann} | {req} | {AUTH[server]} |")

out = f"""# MCP tool inventory

Generated by `python scripts/gen_tools_md.py` from the schema snapshots that CI enforces
(`tests/contract/test_tool_schemas.py`). Every tool has a Pydantic input schema with constraints and
a declared output schema. Write tools need an `idempotency_key` and support `dry_run`.

| Tool | Server | Read/write | Annotations | Required args | Auth |
|---|---|---|---|---|---|
{chr(10).join(rows)}

**Owners (tool allowlists in `agent/config.yaml: tool_allowlist`).** Portfolio tools: {OWNER['portfolio']}.
Marketplace tools: {OWNER['marketplace']}. Workspace tools: {OWNER['workspace']}.

**Resources** (Portfolio): `portfolio://case/{{project_id}}`, `portfolio://proposal/{{proposal_id}}`,
`portfolio://repo/{{project_id}}`, `portfolio://cv`. **Prompts** (Portfolio): `answer_screening_question`,
`proposal_opening`, `evidence_matrix`. **Resource** (Workspace): `workspace://holds`.

## Third-party MCP servers (A5)

| Server | Used for | Trust rationale |
|---|---|---|
| Upwork official MCP (`https://mcp.upwork.com/mcp`) | Live-mode job search, drafts, messages | First-party server of the marketplace itself, OAuth 2.1 scoped to the user; every write is a draft the user confirms on Upwork. |
| GitHub official MCP (`https://api.githubcopilot.com/mcp/`) | Ingesting repo READMEs and code for X3-style portfolio updates | Maintained by GitHub; we use a fine-grained read-only token limited to public repos, and only read tools are allow-listed. |
"""
(ROOT / "docs" / "TOOLS.md").write_text(out, encoding="utf-8")
print(f"wrote docs/TOOLS.md ({len(rows)} tools)")
